/** FNV-1a (32-bit) of `text`'s UTF-16 code units as 8 hex digits: enough to tell a whole store copy from a cut one. */
export function checksum(text: string): string {
  let h = 0x811c9dc5;
  for (let i = 0; i < text.length; i++) {
    h ^= text.charCodeAt(i);
    h = Math.imul(h, 0x01000193) >>> 0;
  }
  return h.toString(16).padStart(8, "0");
}
