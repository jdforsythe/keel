// Spec: std.shells, Conformance "With `tauriDrivers`, a save cut at any byte of `keel.json` or `keel.b.json` leaves a new driver reading the earlier or the new value of every key; a copy of a lower generation or a wrong checksum is not read; with no whole copy and `keel.json` present every call rejects and both files keep their bytes."
// Seed: 1337.
// @vitest-environment happy-dom
// Assumption: as in crash-copies.test.ts (the plugin stand-in of fixtures.ts, `cutSave`, a new driver after `world.restart()`); here the earlier states, the cut write, the file and the byte offset are generated.
// An offset past the end of the saved text is a save that completed before the kill. A value is any text, multi-byte characters included, so an offset can fall inside a character.
import { tauriDrivers } from "@keel/std-tauri";
import fc from "fast-check";
import { afterEach, beforeEach, describe, expect, test } from "vitest";
import {
  BACKUP_FILE,
  begin,
  editCopy,
  end,
  ORIGIN,
  PAGES,
  STORE_FILE,
  settled,
  wrongData,
  wrongSum,
  type World,
} from "./fixtures.ts";

const run = { seed: 1337, numRuns: 100 };
const KEYS = ["a", "b", "c", "d"] as const;
type State = Record<string, string | null>;
const EMPTY: State = { a: null, b: null, c: null, d: null };
let world: World;
const storage = () => tauriDrivers({ origin: ORIGIN }).storage;

const text = fc.string({ maxLength: 16 });
const changes = fc.dictionary(fc.constantFrom(...KEYS), fc.oneof(text, fc.fullUnicodeString({ maxLength: 8 })), {
  minKeys: 1,
});
const file = fc.constantFrom(STORE_FILE, BACKUP_FILE);
const offset = fc.nat(700);

const apply = (from: State, change: Readonly<Record<string, string>>): State => ({ ...from, ...change });
const readAll = async (): Promise<State> => {
  const values = await storage().read([...KEYS]);
  return { a: values[0] ?? null, b: values[1] ?? null, c: values[2] ?? null, d: values[3] ?? null };
};
/** One commit that sets the keys of `change`, expecting what `from` holds. */
const write = async (st: ReturnType<typeof storage>, from: State, change: Readonly<Record<string, string>>) =>
  st.commit(Object.entries(change).map(([key, value]) => ({ key, expect: from[key] ?? null, value })));
const same = (x: State, y: State): boolean => KEYS.every((k) => x[k] === y[k]);

describe("std.shells: a save cut at generated bytes", () => {
  beforeEach(() => {
    world = begin(PAGES[0]);
  });
  afterEach(end);

  test("a save cut at any byte of `keel.json` or `keel.b.json` leaves a new driver reading the earlier or the new value of every key", async () => {
    await fc.assert(
      fc.asyncProperty(
        fc.array(changes, { maxLength: 3 }),
        changes,
        file,
        offset,
        async (history, change, f, bytes) => {
          world.wipe();
          const st = storage();
          let earlier = EMPTY;
          for (const c of history) {
            expect(await write(st, earlier, c)).toBe(true);
            earlier = apply(earlier, c);
          }
          const next = apply(earlier, change);
          world.cutSave(f, bytes);
          await settled(write(st, earlier, change));
          world.restart();
          const after = await readAll();
          for (const k of KEYS) expect([earlier[k], next[k]]).toContain(after[k]);
          expect(same(after, earlier) || same(after, next)).toBe(true);
        },
      ),
      run,
    );
  });

  test("a save cut at any byte, then a second save from the state a new driver read cut at any byte, leaves the earlier or the new value of every key", async () => {
    await fc.assert(
      fc.asyncProperty(
        fc.array(changes, { maxLength: 2 }),
        fc.tuple(changes, file, offset),
        fc.tuple(changes, file, offset),
        async (history, [change1, f1, b1], [change2, f2, b2]) => {
          world.wipe();
          const st = storage();
          let s0 = EMPTY;
          for (const c of history) {
            expect(await write(st, s0, c)).toBe(true);
            s0 = apply(s0, c);
          }
          const s1 = apply(s0, change1);
          world.cutSave(f1, b1);
          await settled(write(st, s0, change1));
          world.restart();
          const read = await readAll();
          expect(same(read, s0) || same(read, s1)).toBe(true);
          const s2 = apply(read, change2);
          world.cutSave(f2, b2);
          await settled(write(storage(), read, change2));
          world.restart();
          const after = await readAll();
          for (const k of KEYS) expect([read[k], s2[k]]).toContain(after[k]);
          expect(same(after, read) || same(after, s2)).toBe(true);
        },
      ),
      run,
    );
  });

  test("a copy of a lower generation is not read", async () => {
    await fc.assert(
      fc.asyncProperty(changes, changes, fc.boolean(), async (first, second, lowInStore) => {
        const v1 = apply(EMPTY, first);
        const bump = Object.fromEntries(KEYS.map((k) => [k, `${second[k] ?? v1[k] ?? ""}!`]));
        const v2 = apply(v1, bump);
        world.wipe();
        expect(await write(storage(), EMPTY, first)).toBe(true);
        const low: Record<string, string> = {
          [STORE_FILE]: world.read(STORE_FILE) ?? "",
          [BACKUP_FILE]: world.read(BACKUP_FILE) ?? "",
        };
        world.restart();
        expect(await write(storage(), v1, bump)).toBe(true);
        const high: Record<string, string> = {
          [STORE_FILE]: world.read(STORE_FILE) ?? "",
          [BACKUP_FILE]: world.read(BACKUP_FILE) ?? "",
        };
        const [lowIn, highIn] = lowInStore ? [STORE_FILE, BACKUP_FILE] : [BACKUP_FILE, STORE_FILE];
        world.wipe();
        world.write(lowIn, low[lowIn] ?? "");
        world.write(highIn, high[highIn] ?? "");
        expect(await readAll()).toEqual(v2);
      }),
      run,
    );
  });

  test("a copy with a wrong checksum is not read", async () => {
    await fc.assert(
      fc.asyncProperty(changes, changes, fc.boolean(), fc.boolean(), async (first, second, badInStore, spoilSum) => {
        const v1 = apply(EMPTY, first);
        const bump = Object.fromEntries(KEYS.map((k) => [k, `${second[k] ?? v1[k] ?? ""}!`]));
        world.wipe();
        expect(await write(storage(), EMPTY, first)).toBe(true);
        const low: Record<string, string> = {
          [STORE_FILE]: world.read(STORE_FILE) ?? "",
          [BACKUP_FILE]: world.read(BACKUP_FILE) ?? "",
        };
        world.restart();
        expect(await write(storage(), v1, bump)).toBe(true);
        const high: Record<string, string> = {
          [STORE_FILE]: world.read(STORE_FILE) ?? "",
          [BACKUP_FILE]: world.read(BACKUP_FILE) ?? "",
        };
        const [badIn, goodIn] = badInStore ? [STORE_FILE, BACKUP_FILE] : [BACKUP_FILE, STORE_FILE];
        world.wipe();
        world.write(badIn, editCopy(high[badIn], spoilSum ? wrongSum : wrongData));
        world.write(goodIn, low[goodIn] ?? "");
        expect(await readAll()).toEqual(v1);
      }),
      run,
    );
  });

  test("with no whole copy and `keel.json` present every call rejects and both files keep their bytes", async () => {
    const spoil = fc.constantFrom<(copy: Record<string, unknown>) => Record<string, unknown>>(wrongSum, wrongData);
    await fc.assert(
      fc.asyncProperty(
        changes,
        fc.constantFrom("cut", "spoiled", "plain"),
        fc.constantFrom("none", "cut", "spoiled"),
        offset,
        spoil,
        spoil,
        text,
        async (change, inStore, inBackup, bytes, spoilA, spoilB, plain) => {
          world.wipe();
          expect(await write(storage(), EMPTY, change)).toBe(true);
          const whole = world.read(STORE_FILE) ?? "";
          world.wipe();
          const cutOf = (t: string): string => t.slice(0, Math.min(bytes, Math.max(0, t.length - 1)));
          world.write(
            STORE_FILE,
            inStore === "cut"
              ? cutOf(whole)
              : inStore === "spoiled"
                ? editCopy(whole, spoilA)
                : JSON.stringify({ k: plain }),
          );
          if (inBackup === "cut") world.write(BACKUP_FILE, cutOf(whole));
          if (inBackup === "spoiled") world.write(BACKUP_FILE, editCopy(whole, spoilB));
          const before = [world.read(STORE_FILE), world.read(BACKUP_FILE)];
          const st = storage();
          expect(await settled(st.get("a"))).toBe("rejected");
          expect(await settled(st.read(["a", "b"]))).toBe("rejected");
          expect(await settled(st.set("a", "x"))).toBe("rejected");
          expect(await settled(st.commit([{ key: "a", expect: null, value: "y" }]))).toBe("rejected");
          expect([world.read(STORE_FILE), world.read(BACKUP_FILE)]).toEqual(before);
        },
      ),
      run,
    );
  });
});
