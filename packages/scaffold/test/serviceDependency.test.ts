import { describe, expect, it } from "vitest";
import { type Files, apply } from "./helpers.ts";

const GEN = {
  id: "app",
  schema: "// generated by @keel/services\nexport {};\n",
  service: "// generated by @keel/services\nexport {};\n",
};

function deps(files: Files): Record<string, string> {
  const pkg: { dependencies: Record<string, string> } = JSON.parse(files.get("package.json") ?? "{}");
  return pkg.dependencies;
}

describe("scaffold service adds the package its files import", () => {
  for (const workspace of [true, false])
    it(`${workspace ? "workspace" : "standalone"}: @keel/services joins dependencies at @keel/server's version, in sorted order`, () => {
      const project = apply("project", { name: "shop", workspace }, new Map());
      expect(deps(project)["@keel/services"]).toBeUndefined();
      const after = apply("service", GEN, project);
      expect(deps(after)["@keel/services"]).toBe(deps(project)["@keel/server"]);
      expect(Object.keys(deps(after))).toEqual(Object.keys(deps(after)).sort());
      expect(after.get("package.json")?.endsWith("}\n")).toBe(true);
    });

  it("a project that already names @keel/services keeps its version", () => {
    const project = apply("project", { name: "shop" }, new Map());
    const pkg: { dependencies: Record<string, string> } = JSON.parse(project.get("package.json") ?? "{}");
    pkg.dependencies["@keel/services"] = "^9.9.9";
    project.set("package.json", `${JSON.stringify(pkg, null, 2)}\n`);
    expect(deps(apply("service", GEN, project))["@keel/services"]).toBe("^9.9.9");
  });
});
