// Spec: k.boundary, clause "No environment value set for a build (`KEEL_SECRET`, `VITE_*`, others but those origins) is in a file under `dist/`."
// k.boundary, Environment "No environment value is in a file `keel build` writes, but the origins `KEEL_PEER_<NAME>` (k.hosting) and, in a shell build, `KEEL_ORIGIN` (k.shell). A browser build's `import.meta.env` holds only `MODE`, `DEV`, `PROD`, `SSR` and `BASE_URL`, exposing no variable by prefix (`VITE_*` too); `process.env.<x>` is never replaced by a value but `NODE_ENV` (k.deploy). Config a browser reads comes through `clientStd` (k.leave)."
// Seed 1337 (the three values are generated by fast-check below). The real binary over the node-plus-client fixture of boundary-support.ts, built once with `KEEL_SECRET`, `KEEL_TEST_VALUE` and `VITE_TEST_VALUE` set to distinct generated values.
// `Page.tsx` and `View.tsx` carry no types reference (`import.meta.env` is typed by Keel's declaration alone, k.boundary Ambient types); they read `VITE_TEST_VALUE` and `KEEL_TEST_VALUE` through `Reflect.get(import.meta.env, …)` and `Object.keys(import.meta.env)`; `load.server.ts` reads `process.env.KEEL_TEST_VALUE`.
import { readFileSync } from "node:fs";
import { join } from "node:path";
import fc from "fast-check";
import { afterAll, beforeAll, describe, expect, test } from "vitest";
import {
  SEED,
  SLOW,
  built,
  cleanup,
  clientTree,
  filesHolding,
  filesUnder,
  materialize,
  withFiles,
} from "./boundary-support.ts";

const [secret, plain, vite] = fc
  .sample(
    fc
      .tuple(
        fc.stringMatching(/^[A-Za-z0-9_-]{32,48}$/),
        fc.stringMatching(/^[A-Za-z0-9_-]{32,48}$/),
        fc.stringMatching(/^[A-Za-z0-9_-]{32,48}$/),
      )
      .filter(([a, b, c]) => new Set([a, b, c]).size === 3),
    { seed: SEED, numRuns: 1 },
  )
  .flat();
const VALUES = { KEEL_SECRET: secret ?? "", KEEL_TEST_VALUE: plain ?? "", VITE_TEST_VALUE: vite ?? "" };

const PROBE =
  "Reflect.set(globalThis, 'envProbe', [Reflect.get(import.meta.env, 'VITE_TEST_VALUE'), Reflect.get(import.meta.env, 'KEEL_TEST_VALUE'), Object.keys(import.meta.env)])\n";
const tree = () => {
  const t = clientTree();
  return withFiles(t, {
    "modules/a/Page.tsx": `${t["modules/a/Page.tsx"] ?? ""}${PROBE}`,
    "modules/w/View.tsx": `${t["modules/w/View.tsx"] ?? ""}${PROBE}`,
    "modules/a/load.server.ts": `${t["modules/a/load.server.ts"] ?? ""}Reflect.set(globalThis, 'srvEnv', process.env.KEEL_TEST_VALUE)\n`,
  });
};

let dir = "";
let peer = "";
let result: ReturnType<typeof built>;
let peerResult: ReturnType<typeof built>;
beforeAll(() => {
  dir = materialize(tree());
  peer = materialize(tree());
  result = built(dir, VALUES);
  peerResult = built(peer, { ...VALUES, KEEL_PEER_API: "https://api.test" });
}, SLOW);
afterAll(() => {
  cleanup(dir);
  cleanup(peer);
});

describe("k.boundary: no environment value set for a build is in a file `keel build` writes", () => {
  test("the build exits 0 and writes files", () => {
    expect(result.status, result.out).toBe(0);
    expect(filesUnder(join(dir, "dist")).length).toBeGreaterThan(0);
  });

  for (const [name, value] of Object.entries(VALUES)) {
    test(`the value of \`${name}\` is in no file under \`dist/\`, \`server.mjs\` and its map included`, () => {
      expect(result.status, result.out).toBe(0);
      expect(value.length).toBeGreaterThanOrEqual(32);
      expect(filesHolding(join(dir, "dist"), value)).toEqual([]);
    });
  }

  test("the values are in no file written outside `dist/` either, `.keel/` included", () => {
    expect(result.status, result.out).toBe(0);
    for (const value of Object.values(VALUES)) {
      expect(filesHolding(join(dir, ".keel"), value)).toEqual([]);
    }
  });

  test("the generated values are distinct and none is a substring of another", () => {
    const vs = Object.values(VALUES);
    for (const a of vs) for (const b of vs) if (a !== b) expect(b.includes(a)).toBe(false);
  });
});

describe("k.boundary: a browser build's `import.meta.env` holds only `MODE`, `DEV`, `PROD`, `SSR` and `BASE_URL`", () => {
  const assets = (root: string): string[] =>
    filesUnder(join(root, "dist")).filter((f) => f.endsWith(".js") && !f.endsWith("server.mjs"));

  test("no variable is exposed by prefix: `VITE_TEST_VALUE` and `KEEL_TEST_VALUE` read from `import.meta.env` are not in any built script", () => {
    expect(result.status, result.out).toBe(0);
    const text = assets(dir)
      .map((f) => readFileSync(f, "utf8"))
      .join("\n");
    expect(text).not.toContain(VALUES.VITE_TEST_VALUE);
    expect(text).not.toContain(VALUES.KEEL_TEST_VALUE);
  });

  test("`Object.keys(import.meta.env)` in the built page lists exactly `BASE_URL`, `DEV`, `MODE`, `PROD`, `SSR`", () => {
    expect(result.status, result.out).toBe(0);
    const text = assets(dir)
      .map((f) => readFileSync(f, "utf8"))
      .join("\n");
    const literals = [...text.matchAll(/Object\.keys\(\{([^}]*)\}\)/g)];
    expect(literals.length, "a built page keeps `Object.keys` over the `import.meta.env` object").toBeGreaterThan(0);
    for (const literal of literals) {
      const keys = [...(literal[1] ?? "").matchAll(/([A-Za-z_$][\w$]*)\s*:/g)].map((m) => m[1]).sort();
      expect(keys).toEqual(["BASE_URL", "DEV", "MODE", "PROD", "SSR"]);
    }
  });

  test("`process.env.<x>` is never replaced by a value but `NODE_ENV`: `server.mjs` still reads `KEEL_TEST_VALUE` from the environment", () => {
    expect(result.status, result.out).toBe(0);
    const text = readFileSync(join(dir, "dist", "api", "server.mjs"), "utf8");
    expect(text).toContain("KEEL_TEST_VALUE");
    expect(text).not.toContain(VALUES.KEEL_TEST_VALUE);
  });
});

describe("k.boundary: the origins `KEEL_PEER_<NAME>` and a shell's `KEEL_ORIGIN` are the only environment values built in", () => {
  test("with `KEEL_PEER_API=https://api.test` the client's `index.html` holds that origin", () => {
    expect(peerResult.status, peerResult.out).toBe(0);
    expect(readFileSync(join(peer, "dist", "web", "index.html"), "utf8")).toContain("https://api.test");
  });

  test("with `KEEL_PEER_API` set, no other environment value is in any file under `dist/`", () => {
    expect(peerResult.status, peerResult.out).toBe(0);
    for (const value of Object.values(VALUES)) expect(filesHolding(join(peer, "dist"), value)).toEqual([]);
  });

  test("with no `KEEL_PEER_API` the origin is in no file", () => {
    expect(result.status, result.out).toBe(0);
    expect(filesHolding(join(dir, "dist"), "https://api.test")).toEqual([]);
  });
});
