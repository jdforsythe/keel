// Spec: k.bundle, clause "A project `vite.config` with `envPrefix: ['KEEL_']`, with `envPrefix: 'KEEL_'`, or with a `define`: `vite build` fails with E1007 `environment config` and writes nothing; a project plugin writing `KEEL_TEST_VALUE`'s value into a page fails it with E1007 `environment value`."
// k.bundle, Environment "No value of a variable set for a build is in a browser asset, whatever the project's Vite config says (`envPrefix` as a string or an array, `define`, a plugin), but k.boundary's public origins and `NODE_ENV`."
// k.bundle, Environment "A project config that sets `envPrefix` or `define` fails each browser build before bundling with E1007 reason `environment config`, chain `vite.config.<ext>`. A value a browser reads comes through `clientStd` (k.leave)."
// k.bundle, Environment "After bundling, an emitted browser file holding the value of a `KEEL_*` variable of 8 characters or more, the public origins excepted, fails the build with E1007 reason `environment value`."
// Seed 1337 (the `KEEL_TEST_VALUE` values are generated by fast-check below). `vite build` with `KEEL_DEPLOYABLE` over a temp project; `node` fixture built as `api`, `static` fixture as `web`, the project's own `vite.config.ts` replaced.
// The plugin is the project's: a `pre` transform that appends the value of `process.env.KEEL_TEST_VALUE` to `Page.tsx`. The controls (a 7-character value, a public origin) must build: the scan is for `KEEL_*` values of 8 characters or more, the origins excepted.
import { existsSync } from "node:fs";
import { join } from "node:path";
import fc from "fast-check";
import { describe, expect, test } from "vitest";
import { SEED, filesHolding, filesUnder, keelRun, linesWith, nodeTree, viteBuild } from "./boundary-support.ts";
import { chainOf, inProject, nodeWith, reasonOf } from "./bundle-support.ts";

const config = (extra: string, plugin = ""): string =>
  `import keel from "@keel/compiler/vite";\nimport { defineConfig } from "vite";\n${plugin}export default defineConfig({ plugins: [keel()${plugin === "" ? "" : ", leak"}]${extra === "" ? "" : `, ${extra}`} });\n`;

const LEAK = `const leak = {
  name: "leak",
  enforce: "pre" as const,
  transform(code: string, id: string): string | null {
    if (!id.endsWith("Page.tsx")) return null;
    return \`\${code}\\nReflect.set(globalThis, 'leak', \${JSON.stringify(process.env.KEEL_TEST_VALUE ?? "")})\\n\`;
  },
};
`;

const CONFIGS = {
  "`envPrefix: ['KEEL_']`": "envPrefix: ['KEEL_']",
  "`envPrefix: 'KEEL_'`": "envPrefix: 'KEEL_'",
  "`envPrefix: ['VITE_', 'KEEL_']`": "envPrefix: ['VITE_', 'KEEL_']",
  "a `define`": "define: { __FROM_CONFIG__: JSON.stringify('from-config') }",
} as const;

describe("k.bundle Environment: a project config that sets `envPrefix` or `define` fails each browser build", () => {
  for (const [name, extra] of Object.entries(CONFIGS)) {
    for (const [placement, deployable] of [
      ["node", "api"],
      ["static", "web"],
    ] as const) {
      test(`${name} in \`vite.config.ts\` of the \`${placement}\` fixture: \`vite build\` exits 1 with one E1007 \`environment config\` whose chain ends \`vite.config.ts\`, and writes nothing`, async () => {
        const files = { ...nodeTree(placement), "vite.config.ts": config(extra) };
        await inProject(files, (dir) => {
          const r = viteBuild(dir, deployable, { KEEL_TEST_VALUE: "kv-0123456789abcdef" });
          expect(r.status, r.out).toBe(1);
          const hits = linesWith(r.out, "E1007");
          expect(hits, r.out).toHaveLength(1);
          expect(reasonOf(hits[0] ?? "")).toBe("environment config");
          expect(chainOf(hits[0] ?? "").at(-1)).toBe("vite.config.ts");
          expect(existsSync(join(dir, "dist", deployable))).toBe(false);
          expect(filesUnder(join(dir, "dist"))).toEqual([]);
        });
      });
    }
  }

  test("`keel build` of the `envPrefix: ['KEEL_']` fixture exits 1 with E1007 `environment config` and no `dist/`", async () => {
    const files = { ...nodeTree("node"), "vite.config.ts": config("envPrefix: ['KEEL_']") };
    await inProject(files, (dir) => {
      const r = keelRun(dir, ["build"], { KEEL_TEST_VALUE: "kv-0123456789abcdef" });
      expect(r.status, r.out).toBe(1);
      expect(r.out).toContain("environment config");
      expect(filesHolding(join(dir, "dist"), "kv-0123456789abcdef")).toEqual([]);
    });
  });

  test("the unchanged project `vite.config.ts` builds with exit 0 and no E1007", async () => {
    await inProject(nodeTree("node"), (dir) => {
      const r = viteBuild(dir, "api", { KEEL_TEST_VALUE: "kv-0123456789abcdef" });
      expect(r.status, r.out).toBe(0);
      expect(linesWith(r.out, "E1007")).toEqual([]);
    });
  });
});

describe("k.bundle Environment: a value of a `KEEL_*` variable in an emitted browser file fails the build", () => {
  const values = fc.sample(fc.stringMatching(/^[A-Za-z0-9]{8,40}$/), { seed: SEED, numRuns: 3 });
  const leaking = () => nodeWith({ "vite.config.ts": config("", LEAK) });

  for (const value of values) {
    test(`a project plugin writing \`KEEL_TEST_VALUE\` (${value.length} characters) into \`Page.tsx\`: \`vite build\` exits 1 with one E1007 \`environment value\`, and writes nothing for \`api\``, async () => {
      await inProject(leaking(), (dir) => {
        const r = viteBuild(dir, "api", { KEEL_TEST_VALUE: value });
        expect(r.status, r.out).toBe(1);
        const hits = linesWith(r.out, "E1007");
        expect(hits, r.out).toHaveLength(1);
        expect(reasonOf(hits[0] ?? "")).toBe("environment value");
        expect(existsSync(join(dir, "dist", "api"))).toBe(false);
        expect(filesHolding(join(dir, "dist"), value)).toEqual([]);
      });
    });
  }

  test("the fixture with the plugin passes `keel check`: the error is the build's", async () => {
    await inProject(leaking(), (dir) => {
      const r = keelRun(dir, ["check"], { KEEL_TEST_VALUE: values[0] ?? "" });
      expect(r.status, r.out).toBe(0);
    });
  });

  test("a `KEEL_TEST_VALUE` of 7 characters, below the scan's floor, builds with exit 0", async () => {
    await inProject(leaking(), (dir) => {
      const r = viteBuild(dir, "api", { KEEL_TEST_VALUE: "abc1234" });
      expect(r.status, r.out).toBe(0);
      expect(linesWith(r.out, "E1007")).toEqual([]);
      expect(filesHolding(join(dir, "dist", "api"), "abc1234")).not.toEqual([]);
    });
  });

  test("the value of `KEEL_PEER_B`, a public origin, written into a page by the plugin builds with exit 0", async () => {
    const origin = "https://peer-b.example.test";
    const files = nodeWith({
      "vite.config.ts": config("", LEAK.replace("process.env.KEEL_TEST_VALUE", "process.env.KEEL_PEER_B")),
    });
    await inProject(files, (dir) => {
      const r = viteBuild(dir, "api", { KEEL_PEER_B: origin });
      expect(r.status, r.out).toBe(0);
      expect(linesWith(r.out, "E1007")).toEqual([]);
      expect(filesHolding(join(dir, "dist", "api"), origin)).not.toEqual([]);
    });
  });
});
