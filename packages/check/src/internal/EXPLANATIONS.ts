/**
 * `keel explain` text for every kernel E code (k.check: at most 120 tokens): the code and its Rules entry,
 * the reason when the spec gives one, one fix example, and the spec section.
 */
export const EXPLANATIONS: ReadonlyMap<string, string> = new Map(
  ROWS.map(([code, rule, why, fix, see]) => [
    code,
    [`${code} ${rule}.`, ...(why === "" ? [] : [why]), `fix: ${fix}`, `see: ${see}`].join("\n"),
  ]),
);
