import { REFUSED_BUILTINS } from "./REFUSED_BUILTINS.ts";

/**
 * The head of a build-time evaluation bundle (k.derived Derivation cache): `__keelObserved`, the record of what the
 * bundle's code asks (`Observed`), and the bundle's own views of what it reads through, which record each question and
 * then ask the real module. `__keelFs` holds the views of `node:fs` and `node:fs/promises` (a read by a file descriptor
 * the views did not open is refused); `__keelProcess`, which every free `process` names (`define`), is the real
 * `process` but for `env`, a view recording each name read (`get`, `in`, a property descriptor, the value before a
 * first write) and a listing of the names, `getBuiltinModule`, which gives these views, and native addons and
 * bindings, refused; `__keelModule` is `node:module` with `createRequire` giving `__keelRequireFor`; `__keelGlobal`,
 * which every free `globalThis` and `global` names, is the global object with these views; `__keelRefusedView` is a
 * built-in of `REFUSED_BUILTINS` whose every function, called or constructed, is refused; `require` is the bundle's
 * own: a Node built-in through these views, a `.json` file a recorded read, any other file refused. A refusal throws
 * E1050 (k.compiler Build-time evaluation). All are the bundle's own bindings: nothing global changes, so another
 * evaluation in the process sees its own record only.
 */
export const OBSERVE_BANNER = [
  'import __keelFsReal from "node:fs";',
  'import __keelFsPromisesReal from "node:fs/promises";',
  'import __keelModuleReal, { createRequire as __keelCreateRequire, isBuiltin as __keelIsBuiltin } from "node:module";',
  'import { resolve as __keelPathResolve } from "node:path";',
  'import { fileURLToPath as __keelFileUrl } from "node:url";',
  "const __keelObserved = { reads: [], probes: [], env: [], envListed: false };",
  `const __keelRefused = new Set(${JSON.stringify(REFUSED_BUILTINS)});`,
  "const __keelRefuse = (what) => { const e = new Error(`${what} at build time: Keel cannot see what it reads, so a build-time evaluation does not run it`); e.code = 'E1050'; throw e; };",
  "const __keelFs = (() => {",
  "  const at = (x) => {",
  "    if (typeof x === 'string') return __keelPathResolve(x);",
  "    if (x instanceof URL) return x.protocol === 'file:' ? __keelFileUrl(x) : undefined;",
  "    if (x instanceof Uint8Array) return __keelPathResolve(Buffer.from(x).toString('utf8'));",
  "    return undefined;",
  "  };",
  "  const fds = new Set();",
  "  const mine = (fd) => { if (typeof fd === 'number' && !fds.has(fd)) __keelRefuse(`a read by file descriptor ${fd}, which the evaluation did not open,`); };",
  "  const note = (kind, a) => {",
  "    if (kind === 'fd') return mine(a[0]);",
  "    const o = kind === 'stream' && a[1] !== null && typeof a[1] === 'object' ? a[1].fd : undefined;",
  "    if (o !== undefined && o !== null) return mine(typeof o === 'object' ? o.fd : o);",
  "    if (typeof a[0] === 'number') return mine(a[0]);",
  "    const f = at(a[0]);",
  "    if (f === undefined) return;",
  "    if (kind === 'read' || kind === 'open' || kind === 'stream') __keelObserved.reads.push(f); else __keelObserved.probes.push([kind, f]);",
  "  };",
  "  const opened = (v) => { if (typeof v === 'number') fds.add(v); else if (v !== null && typeof v === 'object' && typeof v.fd === 'number') fds.add(v.fd); return v; };",
  "  const wrap = (fn, kind, inner) => {",
  "    if (typeof fn !== 'function') return fn;",
  "    const w = function (...a) {",
  "      note(kind, a);",
  "      if (kind !== 'open') return fn.apply(this, a);",
  "      const last = a.length - 1;",
  "      if (last >= 0 && typeof a[last] === 'function') { const done = a[last]; a[last] = function (err, fd) { if (!err) opened(fd); return done.apply(this, arguments); }; }",
  "      const r = fn.apply(this, a);",
  "      return r !== null && typeof r === 'object' && typeof r.then === 'function' ? r.then(opened) : opened(r);",
  "    };",
  "    for (const k of Reflect.ownKeys(fn)) {",
  "      if (k === 'length' || k === 'name' || k === 'prototype' || k === 'arguments' || k === 'caller') continue;",
  "      const d = Reflect.getOwnPropertyDescriptor(fn, k);",
  "      if (d === undefined) continue;",
  "      if (typeof d.value === 'function' && inner !== true) d.value = d.value === fn ? w : wrap(d.value, kind, true);",
  "      Reflect.defineProperty(w, k, d);",
  "    }",
  "    return w;",
  "  };",
  "  const view = (real, notes) => { const v = { ...real }; for (const [k, kind] of Object.entries(notes)) if (typeof real[k] === 'function') v[k] = wrap(real[k], kind); return v; };",
  "  const promises = view(__keelFsPromisesReal, { readFile: 'read', open: 'open', stat: 'exists', lstat: 'exists', access: 'exists', realpath: 'realpath', readlink: 'realpath', readdir: 'list', opendir: 'list' });",
  "  const fs = view(__keelFsReal, {",
  "    readFileSync: 'read', readFile: 'read', openSync: 'open', open: 'open', createReadStream: 'stream',",
  "    readSync: 'fd', read: 'fd', readvSync: 'fd', readv: 'fd', fstatSync: 'fd', fstat: 'fd',",
  "    existsSync: 'exists', exists: 'exists', statSync: 'exists', stat: 'exists', lstatSync: 'exists', lstat: 'exists', accessSync: 'exists', access: 'exists',",
  "    realpathSync: 'realpath', realpath: 'realpath', readlinkSync: 'realpath', readlink: 'realpath',",
  "    readdirSync: 'list', readdir: 'list', opendirSync: 'list', opendir: 'list',",
  "  });",
  "  return { fs: { ...fs, promises }, promises };",
  "})();",
  "const __keelProcess = (() => {",
  "  const real = globalThis.process;",
  "  const seen = new Set();",
  "  const note = (t, k) => { if (typeof k !== 'string' || seen.has(k)) return; seen.add(k); const v = Reflect.get(t, k); __keelObserved.env.push([k, v === undefined ? null : String(v)]); };",
  "  const env = new Proxy(real.env, {",
  "    get(t, k) { note(t, k); return Reflect.get(t, k); },",
  "    has(t, k) { note(t, k); return Reflect.has(t, k); },",
  "    set(t, k, v) { note(t, k); return Reflect.set(t, k, v); },",
  "    deleteProperty(t, k) { note(t, k); return Reflect.deleteProperty(t, k); },",
  "    getOwnPropertyDescriptor(t, k) { note(t, k); return Reflect.getOwnPropertyDescriptor(t, k); },",
  "    ownKeys(t) { __keelObserved.envListed = true; const keys = Reflect.ownKeys(t); for (const k of keys) note(t, k); return keys; },",
  "  });",
  "  const refused = { dlopen: 'process.dlopen (a native addon)', binding: 'process.binding', _linkedBinding: 'process._linkedBinding' };",
  "  return new Proxy(real, {",
  "    get(t, k) {",
  "      if (k === 'env') return env;",
  "      if (k === 'getBuiltinModule') return (id) => __keelBuiltin(id, undefined);",
  "      if (typeof k === 'string' && Object.hasOwn(refused, k)) return () => __keelRefuse(refused[k]);",
  "      return Reflect.get(t, k);",
  "    },",
  "  });",
  "})();",
  "const __keelRefusedViews = new Map();",
  "const __keelRefusedView = (name) => {",
  "  if (__keelRefusedViews.has(name)) return __keelRefusedViews.get(name);",
  "  const fn = (f, what) => new Proxy(f, { apply() { __keelRefuse(what); }, construct() { __keelRefuse(what); } });",
  "  const obj = (o, at) => new Proxy(o, { get(t, k) {",
  "    const v = Reflect.get(t, k);",
  "    const d = Reflect.getOwnPropertyDescriptor(t, k);",
  "    if (typeof k !== 'string' || (d !== undefined && d.configurable === false && d.writable === false)) return v;",
  "    if (typeof v === 'function') return fn(v, `${at}.${k}`);",
  "    return v !== null && typeof v === 'object' && at.split('.').length < 3 ? obj(v, `${at}.${k}`) : v;",
  "  } });",
  "  const view = obj(__keelCreateRequire(import.meta.url)(name), `node:${name}`);",
  "  __keelRefusedViews.set(name, view);",
  "  return view;",
  "};",
  "const __keelBuiltin = (id, real) => {",
  "  const name = String(id).replace(/^node:/, '');",
  "  if (__keelRefused.has(name)) return __keelRefusedView(name);",
  "  if (name === 'fs') return __keelFs.fs;",
  "  if (name === 'fs/promises') return __keelFs.promises;",
  "  if (name === 'process') return __keelProcess;",
  "  if (name === 'module') return __keelModule;",
  "  return (real ?? __keelCreateRequire(import.meta.url))(id);",
  "};",
  "const __keelJson = new Map();",
  "const __keelRequireFor = (base) => {",
  "  const real = __keelCreateRequire(base);",
  "  const req = function require(id) {",
  "    if (typeof id === 'string' && __keelIsBuiltin(id)) return __keelBuiltin(id, real);",
  "    const file = real.resolve(id);",
  "    if (!file.endsWith('.json')) __keelRefuse(`require(${JSON.stringify(String(id))}) of a file`);",
  "    if (!__keelJson.has(file)) { __keelObserved.reads.push(file); __keelJson.set(file, JSON.parse(__keelFsReal.readFileSync(file, 'utf8'))); }",
  "    return __keelJson.get(file);",
  "  };",
  "  return Object.assign(req, { resolve: real.resolve, cache: real.cache, extensions: real.extensions, main: real.main });",
  "};",
  "const __keelModule = new Proxy(__keelModuleReal, { get(t, k) { if (k === 'createRequire') return __keelRequireFor; if (k === 'Module') return __keelModule; return Reflect.get(t, k); } });",
  "const __keelGlobal = new Proxy(globalThis, { get(t, k) { if (k === 'process') return __keelProcess; if (k === 'global' || k === 'globalThis') return __keelGlobal; return Reflect.get(t, k); } });",
  "const require = __keelRequireFor(import.meta.url);",
].join("\n");
