// tasks/COVERAGE.md from an evidence report (tooling/evidence.mjs): tables A (clauses by section), B (tests by unit
// and kind), C (mutation), D (line and branch coverage), and what the numbers do not show.
import { RUNGS, TEST_FIELDS } from "./evidence.mjs";

const row = (cells) => `| ${cells.join(" | ")} |`;
const head = (cols, right) => [row(cols), row(cols.map((_, i) => (i >= right ? "---:" : "---")))];
const pct = (m) => (m === null ? "" : `${m.pct}%`);

/** The markdown text of `report`. */
export function renderMarkdown(report) {
  const { ledger, tests, mutation, coverage } = report;
  const out = [
    "_Generated by `pnpm evidence:report --markdown` from `tooling/ledger/evidence.json`. Do not edit by hand._",
    "",
    "# Test coverage and evidence",
    "",
    `Commit ${report.commit.slice(0, 8)}, generated ${report.generatedAt}. Sources: \`tooling/ledger/ledger.json\` (tables A and C), the test files under \`packages/*/\` and \`apps/*/\` (table B), each unit's \`coverage/\` summary from \`pnpm coverage\` (table D). The counting rules are in the header of \`tooling/evidence.mjs\`.`,
    "",
    "## Ledger totals",
    "",
    `${ledger.items} items (${ledger.clauses.total} clauses, ${ledger.exports.total} exports, ${ledger.a11y.total} route and WCAG items), ${ledger.verified} verified (above \`none\`), ${ledger.unsafe} unsafe, ${ledger.negativeTypes ?? 0} negative type expectations, ${mutation.stale} stale mutation claims. Items holding any evidence at each rung: ${RUNGS.filter(
      (r) => r !== "none",
    )
      .map((r) => `${ledger.evidenceByRung[r] ?? 0} ${r}`)
      .join(", ")}; an item can hold more than one rung.`,
    "",
    "## A. Spec clauses by section",
    "",
    "A clause is one conformance sentence of a section. The rung columns give each clause's highest rung.",
    "",
    ...head(["section", "status", "clauses", "verified", ...RUNGS], 2),
  ];
  for (const [id, s] of Object.entries(ledger.clauses.sections).sort(([a], [b]) => a.localeCompare(b)))
    out.push(row([id, s.status, s.total, s.verified, ...RUNGS.map((r) => s.byRung[r])]));
  const sectionCount = Object.keys(ledger.clauses.sections).length;
  out.push(
    row([
      `total (${sectionCount} sections)`,
      "",
      ledger.clauses.total,
      ledger.clauses.verified,
      ...RUNGS.map((r) => ledger.clauses.byRung[r]),
    ]),
    "",
    "Exports and route and WCAG items by highest rung:",
    "",
    ...head(["items", "total", "verified", ...RUNGS], 1),
    row(["exports", ledger.exports.total, ledger.exports.verified, ...RUNGS.map((r) => ledger.exports.byRung[r])]),
    row(["route and WCAG", ledger.a11y.total, ledger.a11y.verified, ...RUNGS.map((r) => ledger.a11y.byRung[r])]),
    "",
    "## B. Tests by unit and kind",
    "",
    "Static counts from the files, not a run. Fails and skip/todo are already inside the case counts.",
    "",
    ...head(["unit", ...TEST_FIELDS], 1),
  );
  for (const [u, t] of Object.entries(tests.packages)) out.push(row([u, ...TEST_FIELDS.map((f) => t[f])]));
  out.push(
    row(["total", ...TEST_FIELDS.map((f) => tests.totals[f])]),
    "",
    "## C. Mutation by unit",
    "",
    "Score and threshold come from the ledger. The report date is the day `reports/mutation/mutation.json` was written. A claim is stale when its file's sha256 differs from the claim's; stale claims are left out of the score. Justified counts the survivors `mutation-justified.json` covers; the score without them leaves them out of the count, and the threshold is judged on the score alone.",
    "",
    ...head(["unit", "score", "justified", "score without them", "threshold", "report date", "claims", "stale"], 1),
  );
  const unmutated = [];
  for (const [u, m] of Object.entries(mutation.packages)) {
    if (m.reason !== null) unmutated.push(u);
    else
      out.push(
        row([
          u,
          m.score,
          m.justified ?? 0,
          m.scoreJustified ?? m.score,
          m.threshold,
          m.reportDate ?? "",
          m.claims,
          m.stale,
        ]),
      );
  }
  out.push(
    "",
    `No mutation run (${unmutated.length}): ${unmutated.join(", ") || "none"}.`,
    "",
    "## D. Line and branch coverage",
    "",
    "Lines, branches, functions and statements of `src/` and `unsafe/` (`modules/` for an app) that the unit's tests executed, from `pnpm coverage`. A row names the commit it was measured at; `dirty` means the unit's files differed from that commit.",
    "",
    ...head(["unit", "lines", "branches", "functions", "statements", "commit", "dirty", "measured"], 1),
  );
  const unmeasured = [];
  for (const [u, c] of Object.entries(coverage.packages)) {
    if (c.reason !== null) unmeasured.push(u);
    else
      out.push(
        row([
          u,
          pct(c.lines),
          pct(c.branches),
          pct(c.functions),
          pct(c.statements),
          (c.commit ?? "").slice(0, 8),
          c.dirty ? "yes" : "no",
          (c.measuredAt ?? "").slice(0, 10),
        ]),
      );
  }
  out.push(
    "",
    `Not measured (${unmeasured.length}): ${unmeasured.join(", ") || "none"}.`,
    "",
    "## What this does not show",
    "",
    "- Static counts are not runs. A case may be skipped or failing.",
    "- A rung of `example` means a passing test references the item, which can be one case. It is not a proof and not a bound on inputs.",
    "- A verified clause means a conformance test cites it, not that the test is strong. Mutation scores are the check on that.",
    "- Coverage is the lines and branches the tests executed, not behaviour they proved: an executed line can still be wrong.",
    "- `probabilistic` needs a seeded property of at least 100 runs, `exhaustive` a bounded `explore`, `proven` a type-level test, a closed `explore` or a `prove`. `monitored` is production only.",
    "- Property calls are counted per call, not per generated run.",
    "- The ledger file is as of its last `pnpm ledger` run; the working tree may have moved since.",
    "",
  );
  return out.join("\n");
}
