// The coverage options `keelConfig` adds when `KEEL_COVERAGE=1` (tooling/coverage.mjs sets it): v8 coverage of
// the package's own code, written as `coverage/coverage-summary.json` and nothing else.
import fs from "node:fs";
import path from "node:path";
import type { ViteUserConfig } from "vitest/config";

type Coverage = NonNullable<NonNullable<ViteUserConfig["test"]>["coverage"]>;

/** The first line of a file tooling/generate.mjs writes. */
const GENERATED = /generated by tooling\/generate\.mjs/i;
const CODE = /\.(?:ts|tsx|mts|cts|js|jsx|mjs)$/;

/** Files under `dir` (relative to `root`) whose first line says tooling/generate.mjs wrote them. */
function generatedIn(root: string, dir: string): string[] {
  const abs = path.join(root, dir);
  if (!fs.existsSync(abs)) return [];
  const out: string[] = [];
  for (const e of fs.readdirSync(abs, { withFileTypes: true })) {
    const rel = `${dir}/${e.name}`;
    if (e.isDirectory()) out.push(...generatedIn(root, rel));
    else if (CODE.test(e.name)) {
      const first = fs.readFileSync(path.join(abs, e.name), "utf8").split("\n", 1)[0] ?? "";
      if (GENERATED.test(first)) out.push(rel);
    }
  }
  return out;
}

/**
 * Measured: `src/**` and `unsafe/**` (a package), `modules/**` (an app). Left out: tests (`test/`, `conformance/`,
 * `*.test.*`, negative type tests `*.test-d.*`), type-only files (`types/`, `*.d.ts`) and the files tooling/generate.mjs writes.
 */
export function coverageOptions(root: string): Coverage {
  const dirs = ["src", "unsafe", "modules"];
  return {
    enabled: true,
    provider: "v8",
    include: dirs.map((d) => `${d}/**/*.{ts,tsx,mts,cts,js,jsx,mjs}`),
    exclude: [
      "**/test/**",
      "**/conformance/**",
      "**/*.test.*",
      "**/*.test-d.*",
      "**/types/**",
      "**/*.d.ts",
      ...dirs.flatMap((d) => generatedIn(root, d)),
    ],
    reporter: ["json-summary"],
    reportsDirectory: "coverage",
    clean: true,
    reportOnFailure: true,
  };
}
