import { chromium } from "@playwright/test";
const b = await chromium.launch(); const p = await b.newPage();
const errors = []; p.on("pageerror", (e) => errors.push(String(e)));
const txt = () => p.evaluate(() => document.querySelector("#todos\\.main")?.innerText.replace(/\s+/g, " ").trim().slice(0, 300));
await p.goto("http://localhost:4173/", { waitUntil: "networkidle" });
await p.fill("#form1\\:name", "Groceries"); await p.click("#todos\\.addList"); await p.waitForTimeout(200);
await p.click('a[href^="/lists/"]'); await p.waitForTimeout(300);
const titleInput = await p.evaluate(() => [...document.querySelectorAll("input")].map((i) => i.id));
const tid = titleInput.find((i) => /title/i.test(i)); await p.fill(`[id="${tid}"]`, "Milk");
await p.click("#todos\\.addTodo"); await p.waitForTimeout(200);
const afterAdd = await txt();
const checkbox = await p.evaluate(() => document.querySelector('input[type="checkbox"]')?.id ?? null);
if (checkbox) await p.click(`[id="${checkbox}"]`); await p.waitForTimeout(200);
const afterToggle = await txt();
const checked1 = await p.evaluate(() => document.querySelector('input[type="checkbox"]')?.checked);
await p.click("#todos\\.undo"); await p.waitForTimeout(200);
const checked2 = await p.evaluate(() => document.querySelector('input[type="checkbox"]')?.checked);
await p.screenshot({ path: process.argv[2], fullPage: true });
console.log(JSON.stringify({ afterAdd, afterToggle, checked1, checked2, errors }, null, 1));
await b.close();
